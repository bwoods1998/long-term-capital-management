def cells(phase):
    if phase == "w1":
        return [c + ({},) for c in widened_grid(1000)]
    if phase == "wstress":
        return [c + ({"run2": True},) for c in stress2_grid(2000)]
    if phase in ("w2", "w2x", "w3", "w3x"):
        spec = json.load(open(os.path.join(HERE, f"{phase}.cells.json")))
        return [(c["lab"], c["gen"], c["R"], c.get("T", 120), c.get("opts", {})) for c in spec]
    if phase == "wpilot":
        corner = dict(rho_day=0.15, phi_day=0.20, drift_sd=0.0020, **N3)
        return [("N3|bothTC|AR20|phi0.20", dict(nbar=85, **corner, **shape_kw("TC", "skew")[1]), 300, 120, {}),
                ("N3|bothT|AR20|phi0.20", dict(nbar=8, **corner, **shape_kw("T", "skew")[1]), 300, 120, {}),
                ("N3|bothC|AR20|phi0.20|cnt", dict(nbar=3, **corner, **shape_kw("C", "skew")[1], cnt_kappa=CNT_KAPPA,
                                                   mw_knife=CF.CAP), 300, 120, {}),
                ("N3|dayskewTC|AR20|phi0.20|cnt", dict(nbar=5, **corner, **shape_kw("TC", "sym")[1],
                                                       cnt_kappa=CNT_KAPPA, mw_knife=CF.CAP), 300, 120, {})]
    raise ValueError(phase)


def _job(args):
    phase, lab, kw, R, T, seed, opts = args
    t0 = time.time()
    out, info = simulate(Gen2(**kw), R, T, seed, run2=opts.get("run2", False), unweighted=opts.get("unweighted", False))
    path = os.path.join(ARR, f"{phase}_{seed}.npz")
    np.savez_compressed(path, **out)
    return lab, json.dumps(kw, sort_keys=True), R, T, seed, path, info, time.time() - t0, opts


def run(phase, workers, chunk=500):
    from multiprocessing import get_context
    jobs = []
    seed = SEEDS[phase]
    for lab, kw, R, T, opts in cells(phase):
        for c in range(0, R, chunk):
            seed += 1
            jobs.append((phase, lab, kw, min(chunk, R - c), T, seed, opts))
    jobs.sort(key=lambda j: -j[2]["nbar"] * j[4])
    t0 = time.time()
    index = os.path.join(HERE, f"calib_v2.{phase}.index.jsonl")
    with get_context("fork").Pool(workers) as pool, open(index, "w") as fh:
        for k, (lab, kws, R, T, sd, path, info, secs, opts) in enumerate(pool.imap_unordered(_job, jobs), 1):
            fh.write(json.dumps({"phase": phase, "cell": lab, "gen": json.loads(kws), "R": R, "T": T, "seed": sd,
                                 "path": path, "info": info, "opts": opts, "secs": round(secs, 1)}) + "\n")
            fh.flush()
            if k % 40 == 0 or k == len(jobs):
                print(f"{phase}: {k}/{len(jobs)} jobs, {time.time() - t0:.0f}s", flush=True)


def pilot():
    """The prefilter against full computation on the new shapes (as pilot_any.py: every entry at which the full p is
    <= 0.020 with the guards, or the full q <= 0.020 with mean a < 0, must carry the full value), the realized
    money-weighted and event-weighted mean a of the knife-edge nulls, and the realized crash-day share."""
    for lab, kw, R, T, opts in cells("wpilot"):
        g = Gen2(**kw)
        pre, info = simulate(g, R, T, 4343)
        full, _ = simulate(g, R, T, 4343, full_p=True)
        P_full = np.where(np.isnan(full["P"]), 9.0, full["P"])
        P_pre = np.where(np.isnan(pre["P"]), 9.0, pre["P"])
        need = (P_full <= 0.020) & full["g"]
        bad = need & (np.abs(P_pre - P_full) > 1e-12)
        Q_full = np.where(np.isnan(full["Q"]), 9.0, full["Q"])
        Q_pre = np.where(np.isnan(pre["Q"]), 9.0, pre["Q"])
        needq = (Q_full <= 0.020) & full["neg"]
        badq = needq & (np.abs(Q_pre - Q_full) > 1e-12)
        print(f"{lab} n{kw['nbar']}: entries with full p <= 0.020 and the guards {int(need.sum())}, disagreements "
              f"{int(bad.sum())}; entries with full q <= 0.020 and mean a < 0 {int(needq.sum())}, disagreements "
              f"{int(badq.sum())}; realized mw {info['mw_mean_a_bp']:+.2f} bp, ew {info['ew_mean_a_bp']:+.2f} bp, crash "
              f"share {info['crash_share']:.4f}", flush=True)
    # the day law: mean, variance, crash share of each new shape (unconditional, from the stationary regime)
    for day in NEW_DAYS:
        g = Gen2(day=day)
        _, h, eps = _joint(g, np.random.default_rng(5), 4_000_000)
        x = g.vol_sd * np.random.default_rng(6).standard_normal(4_000_000)
        p = crash_p(g, x) if day.endswith("cl") else np.full(4, CRASH_P)
        print(f"day law {day}: mean {eps.mean():+.4f} var {eps.var():.4f} skew {((eps - eps.mean()) ** 3).mean() / eps.std() ** 3:+.2f}"
              f" mean crash probability {float(np.mean(p)):.4f}", flush=True)


