"""calib_v2.py: PREREG-EVL-6's calibration on the WIDENED plausible grid of the captain's D14 (SYNTHETIC DATA ONLY).

Nothing here reads the live lane: no events.sqlite, no live.sqlite, no market data, no price, no return, no look, no
band. Every number comes from the generator below.

THE GENERATOR is calib_final.py's (the judge's, with the checks' structures and D4's values and guard), copied here
with these additions only; every earlier cell is generated by calib_final.py and is unchanged:
  - THREE NEW DAY SHAPES (D14; re-check 1's blocker), each day still mean 0, variance 1:
      crasht3   - crash days with a t(3) body: 5% of sessions N(-3, 1), the rest m + s x unit t(3) (calib_final's crash
                  days have a normal body there);
      crashcl   - crash days clustered in high-volatility regimes: the crash probability of session t is
                  p_t = 0.05 exp(2 x_t) / E[exp(2 x)], at most 0.09 (x_t the volatility regime's log state, stationary
                  sd 0.3; the mean of p_t is about 4.7%), and m, s are set from p_t so the day has mean 0, variance 1;
      crasht3cl - both together.
  - COUNTS THAT FOLLOW THE SIZE OF THE DAY SHOCK (check 1's structure, D14) on every day shape: the control's count x
    exp(0.3 min(|eps_t|, 4)) / its mean, the knife edge set on MONEY weights min(n, 14), computed numerically from
    the joint law of (x_t, eps_t) (so the clustered shapes' coupling of h_t and eps_t is inside it).
  - OTHER STRUCTURES (re-check 1; reported, not in the grid): the family drift's innovation correlated with the day
    shock's innovation (drift_day_corr); count-residual coupling with the knife set on money weights (kappa_knife).
Everything a rule needs is stored per (program, session) exactly as in calib_final.py (search_final.py reads it).

Usage: calib_v2.py pilot | run --phase P [--workers N]
"""
