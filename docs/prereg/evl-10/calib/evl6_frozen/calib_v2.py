EVS = {"sym": dict(jump_left=0.5), "skew": dict(ev_left=1.4, ev_right=0.6, jump_left=0.8)}
# shape names: calib_final's dayskew (crash, symmetric events) and both (crash, skewed events) carry over; the new day
# shapes are suffixed T (t(3) body), C (clustered), TC (both)
DAYS2 = {"T": "crasht3", "C": "crashcl", "TC": "crasht3cl"}


def shape_kw(day_tag, ev):
    """day_tag: 'sym' (t(3) days), 'crash' (calib_final's crash days), 'T', 'C', 'TC'; ev: 'sym' or 'skew'."""
    day = {"sym": "t3", "crash": "crash"}.get(day_tag) or DAYS2[day_tag]
    if day_tag == "sym":
        name = "sym" if ev == "sym" else "evskew"
    else:
        base = "dayskew" if ev == "sym" else "both"
        name = base if day_tag == "crash" else base + day_tag
    return name, dict(day=day, **EVS[ev])


DRIFTS = CF.DRIFTS


def widened_grid(R):
    """D14's additions to the plausible grid: (a) the three new day shapes x two event shapes x rho_day 0.05, 0.15 x
    phi_day 0.10, 0.15, 0.20 x three drifts x five rates; (b) counts that follow the size of the day shock (kappa 0.3,
    knife on money weights min(n, 14)) on every day shape x two event shapes x rho_day 0.05, 0.15 x phi_day 0.10,
    0.15, 0.20 x three drifts at 3, 5 and 8 events a session. (At rho_day 0 there is no day shock: those cells are
    calib_final's.)"""
    out = []
    for dt in ("T", "C", "TC"):
        for ev in ("sym", "skew"):
            name, kw = shape_kw(dt, ev)
            for rho in (0.05, 0.15):
                for phi in (0.10, 0.15, 0.20):
                    for dname, dkw in DRIFTS:
                        for nb in RATES:
                            out.append((f"N3|{name}|{dname}|phi{phi:.2f}", dict(nbar=nb, rho_day=rho, phi_day=phi, **N3,
                                                                               **kw, **dkw), R, 120))
    for dt in ("sym", "crash", "T", "C", "TC"):
        for ev in ("sym", "skew"):
            name, kw = shape_kw(dt, ev)
            for rho in (0.05, 0.15):
                for phi in (0.10, 0.15, 0.20):
                    for dname, dkw in DRIFTS:
                        for nb in (8, 5, 3):
                            out.append((f"N3|{name}|{dname}|phi{phi:.2f}|cnt", dict(nbar=nb, rho_day=rho, phi_day=phi,
                                                                                   cnt_kappa=CNT_KAPPA, mw_knife=CF.CAP,
                                                                                   **N3, **kw, **dkw), R, 120))
    return out


def stress2_grid(R):
    """STRESSES of the new shapes and re-check 1's OTHER STRUCTURES (reported, not binding), at the old corner
    (crash days with a normal body, skewed events, 20 bp, rho_day 0.15, phi_day 0.20) and at the new one (t(3)-body
    crash days clustered in high-volatility regimes, the same otherwise)."""
    out = []
    corner = dict(rho_day=0.15, phi_day=0.20, drift_sd=0.0020, **N3)
    _, both = shape_kw("crash", "skew")
    _, bothTC = shape_kw("TC", "skew")
    for nm, sh in (("both", both), ("bothTC", bothTC)):
        for nb in (85, 30):
            out.append((f"X|drift-day corr .3|N3|{nm}|AR20", dict(nbar=nb, **corner, **sh, drift_day_corr=0.3), R, 120))
        out.append((f"X|vol AR.97|N3|{nm}|AR20", dict(nbar=85, **corner, **sh, vol_rho=0.97), R, 120))
        for nb in (150, 110):
            out.append((f"X|rate|N3|{nm}|AR20", dict(nbar=nb, **corner, **sh), R, 120))
        out.append((f"X|drift AR.95|N3|{nm}|AR20", dict(nbar=85, **{**corner, "drift_rho": 0.95}, **sh), R, 120))
        for nb in (8, 5, 3):
            for kp in (0.01, 0.02):
                out.append((f"X|kappa{kp} MW|N3|{nm}|AR20", dict(nbar=nb, **corner, **sh, kappa=kp, kappa_knife=1),
                            R, 120))
    # the new day shapes beyond the grid: phi_day 0.25, rho_day 0.30, a 30 bp drift
    for dt in ("T", "C", "TC"):
        nm, sh = shape_kw(dt, "skew")
        for nb in (85, 30, 8):
            out.append((f"S|phi.25|N3|{nm}|AR20", dict(nbar=nb, rho_day=0.15, phi_day=0.25, drift_sd=0.0020, **N3,
                                                       **sh), R, 120))
            out.append((f"S|rho.30|N3|{nm}|AR20", dict(nbar=nb, rho_day=0.30, phi_day=0.10, drift_sd=0.0020, **N3,
                                                       **sh), R, 120))
            out.append((f"S|AR30|N3|{nm}", dict(nbar=nb, rho_day=0.05, phi_day=0.10, drift_sd=0.0030, **N3, **sh), R,
                        120))
        out.append((f"S|phi.25|N3|{nm}|AR20|cnt", dict(nbar=3, rho_day=0.15, phi_day=0.25, drift_sd=0.0020,
                                                       cnt_kappa=CNT_KAPPA, mw_knife=CF.CAP, **N3, **sh), R, 120))
    return out


