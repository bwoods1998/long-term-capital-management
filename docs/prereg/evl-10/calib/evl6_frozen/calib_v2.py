NEW_DAYS = ("crasht3", "crashcl", "crasht3cl")
CRASH_P, CRASH_K, CL_GAMMA, CL_MAX = 0.05, 3.0, 2.0, 0.09
CNT_KAPPA = 0.3


@dataclasses.dataclass(frozen=True)
class Gen2(CF.Gen):
    drift_day_corr: float = 0.0
    kappa_knife: int = 0


def crash_p(g, x):
    """The clustered crash probability of each session from the volatility regime's log state x."""
    return np.minimum(CRASH_P * np.exp(CL_GAMMA * x) / math.exp(CL_GAMMA ** 2 * g.vol_sd ** 2 / 2.0), CL_MAX)


def day_innov2(rng, g, R, x=None):
    """(eps, crash-hit) of unit variance and mean 0 (given the regime, for the clustered shapes)."""
    if g.day not in NEW_DAYS:
        return CF.day_innov(rng, g.day, R)
    k = CRASH_K
    p = crash_p(g, x) if g.day.endswith("cl") else CRASH_P
    m = p * k / (1.0 - p)
    s = np.sqrt((1.0 - p * (k * k + 1.0)) / (1.0 - p) - m * m)
    hit = rng.random(R) < p
    crash = rng.normal(-k, 1.0, R)
    body = CF.unit_t3(rng, R) if "t3" in g.day else rng.standard_normal(R)
    return np.where(hit, crash, m + s * body), hit


def _joint(g, rr, M):
    """M draws of (x, h, eps) from the stationary law (x ~ N(0, vol_sd^2))."""
    x = g.vol_sd * rr.standard_normal(M)
    eps, _ = day_innov2(rr, g, M, x)
    return x, np.exp(x - g.vol_sd ** 2), eps


def count_norm(g):
    """E[exp(kappa min(|eps|, 4))] (the count multiplier's mean)."""
    if g.cnt_kappa <= 0:
        return 1.0
    if g.day not in NEW_DAYS:
        rr = np.random.default_rng(424242)
        e_, _ = CF.day_innov(rr, g.day, 2_000_000)
        return float(np.exp(g.cnt_kappa * np.minimum(np.abs(e_), 4.0)).mean())
    _, _, e_ = _joint(g, np.random.default_rng(424242), 2_000_000)
    return float(np.exp(g.cnt_kappa * np.minimum(np.abs(e_), 4.0)).mean())


def knife_mu2(g):
    """mu_family of the null: the money-weighted knife (mw_knife) and the count-residual money knife (kappa_knife)."""
    mu = g.mu_family
    if g.mw_knife:
        if g.day not in NEW_DAYS:
            mu = CF.money_knife_mu(g)
        else:
            rr = np.random.default_rng(434343)
            M = 4_000_000
            _, h, eps = _joint(g, rr, M)
            mult = np.exp(g.cnt_kappa * np.minimum(np.abs(eps), 4.0))
            mult = mult / mult.mean()
            n = rr.poisson(g.nbar * mult * rr.gamma(g.shape_n, 1.0 / g.shape_n, M))
            w = np.minimum(n, g.mw_knife).astype(float)
            w_ev = float((w * h * eps).sum() / w.sum())
            mu = -g.skill - g.sd_day() * math.sqrt(1 - g.phi_day ** 2) * w_ev
    if g.kappa and g.kappa_knife:
        rr = np.random.default_rng(24_680)
        Gk = rr.gamma(g.shape_n, 1.0 / g.shape_n, 4_000_000)
        nk = rr.binomial(rr.poisson(g.nbar / g.p_read * Gk), g.p_read)
        wk = np.minimum(nk, CF.CAP).astype(float)
        mu = mu - g.kappa * float((wk * (1.0 / g.shape_n - (Gk - 1.0))).sum() / wk.sum())
    return mu


def simulate(g: Gen2, R: int, T: int, seed: int, run2: bool = False, unweighted: bool = False,
             full_p: bool = False):
    """calib_final.simulate with the day shapes, the count coupling's knife and the drift-day correlation above."""
    rng = np.random.default_rng(seed)
    U = g.U
    sector = rng.choice(len(CF.SECTOR_W), size=U, p=CF.SECTOR_W)
    logw = -g.zipf_s * np.log(np.arange(1, U + 1))
    isig = np.exp(rng.uniform(math.log(g.sig_lo), math.log(g.sig_hi), (R, U)))
    beta = np.array(g.beta_mean)[None, None, :] + g.beta_sd * rng.standard_normal((R, U, 3))
    tau = None
    if g.issuer_tau > 0:
        tau = g.issuer_tau * rng.standard_normal((R, U))
        tau -= tau.mean(axis=1, keepdims=True)
    last = np.full((R, U), -10_000, np.int32)
    lvol = rng.standard_normal(R) * g.vol_sd
    D = rng.standard_normal(R) * g.drift_sd if g.drift_sd > 0 else np.zeros(R)
    z, _ = day_innov2(rng, g, R, lvol)
    sd_c = g.sd_day()
    jmean = g.jump_p * g.jump_size * (1.0 - 2.0 * g.jump_left)
    rate_c = g.nbar / g.p_read
    hot_add = math.log(g.hot_mult)
    rows = np.arange(R)
    gflips = np.where(np.random.default_rng(seed + 77_777).random((CF.B_ISS_G, U)) < 0.5, -1.0, 1.0)
    mu_family = knife_mu2(g)
    Emult = count_norm(g)
    recs = [CF.Record(R, T, U, 0, unweighted)]
    if run2:
        recs.append(CF.Record(R, T, U, CF.S_RUN, unweighted))
    Sglob = np.zeros(R, np.int64)
    mw_num = mw_den = ew_num = ew_den = 0.0
    crash_n = 0
    S_RUN, CAP, MARGIN, TIE = CF.S_RUN, CF.CAP, CF.MARGIN, CF.TIE
    for t in range(1, T + 1):
        ti = t - 1
        lvol = g.vol_rho * lvol + math.sqrt(1 - g.vol_rho ** 2) * g.vol_sd * rng.standard_normal(R)
        h = np.exp(lvol - g.vol_sd ** 2)
        if g.drift_day_corr:
            eps, hitc = day_innov2(rng, g, R, lvol)
            innov = g.drift_day_corr * eps + math.sqrt(1 - g.drift_day_corr ** 2) * rng.standard_normal(R)
            D = g.drift_rho * D + math.sqrt(1 - g.drift_rho ** 2) * g.drift_sd * innov
        else:
            if g.drift_sd > 0:
                D = g.drift_rho * D + math.sqrt(1 - g.drift_rho ** 2) * g.drift_sd * rng.standard_normal(R)
            eps, hitc = day_innov2(rng, g, R, lvol)
        crash_n += int(hitc.sum())
        z = g.phi_day * z + math.sqrt(1 - g.phi_day ** 2) * eps
        c_day = sd_c * z
        s_sec = g.sd_sector * CF.unit_t3(rng, (R, len(CF.SECTOR_W)))
        f_fac = g.sd_factor * CF.unit_t3(rng, (R, 3))
        b = g.b_mu + g.b_sd * rng.standard_normal(R)
        elig = (t - last) > g.cooldown
        n_el = elig.sum(axis=1)
        Gt = rng.gamma(g.shape_n, 1.0 / g.shape_n, R)
        mult = np.exp(g.cnt_kappa * np.minimum(np.abs(eps), 4.0)) / Emult if g.cnt_kappa > 0 else 1.0
        nC = np.minimum(rng.poisson(rate_c * mult * Gt), n_el)
        nmax = int(nC.max())
        if nmax == 0:
            continue
        keys = logw[None, :] + rng.gumbel(size=(R, U))
        hot = np.where(rng.random(R) < g.hot_p, rng.integers(0, len(CF.SECTOR_W), R), -1)
        keys += np.where(sector[None, :] == hot[:, None], hot_add, 0.0)
        keys[~elig] = -np.inf
        idx = np.argpartition(-keys, nmax - 1, axis=1)[:, :nmax] if nmax < U else np.tile(np.arange(U), (R, 1))
        kv = np.take_along_axis(keys, idx, axis=1)
        idx = np.take_along_axis(idx, np.argsort(-kv, axis=1), axis=1)
        mask = np.arange(nmax)[None, :] < nC[:, None]
        er = np.broadcast_to(rows[:, None], mask.shape)[mask]
        ei = idx[mask]
        last[er, ei] = t
        E = er.size
        sel = rng.random(E) < g.p_read
        noise = isig[er, ei] * CF.unit_t3(rng, E, g.ev_left, g.ev_right)
        common = c_day[er] + s_sec[er, sector[ei]] + (beta[er, ei, :] * f_fac[er, :]).sum(axis=1)
        a = mu_family + D[er] + h[er] * (common + noise)
        if g.kappa:
            a = a + g.kappa * (1.0 / g.shape_n - (Gt[er] - 1.0))
        if g.lam:
            a = a - g.lam * (h[er] - 1.0)
        if g.jump_p > 0:
            hit = rng.random(E) < g.jump_p
            sgn = np.where(rng.random(E) < g.jump_left, -1.0, 1.0)
            a = a + hit * sgn * g.jump_size - jmean
        if tau is not None:
            a = a + tau[er, ei]
        a = a + g.skill * sel
        a = np.maximum(a, -1.0)
        rr_ = a + b[er]
        cs = np.cumsum(sel)
        first = np.r_[True, er[1:] != er[:-1]]
        start_idx = np.maximum.accumulate(np.where(first, np.arange(E), 0))
        pos = cs - (cs[start_idx] - sel[start_idx])
        top = sel & (pos <= CAP)
        pr, pi_, pa, prr = er[sel], ei[sel], a[sel], rr_[sel]
        nP = np.bincount(pr, minlength=R)
        sP = np.bincount(pr, pa, R)
        sR = np.bincount(pr, prr, R)
        tA = np.bincount(er[top], a[top], R)
        tR = np.bincount(er[top], rr_[top], R)
        nCt = np.bincount(er, minlength=R)
        sC = np.bincount(er, a, R)
        has = nP > 0
        Bt = np.where(has, sP / np.maximum(nP, 1), 0.0)
        Ct = np.where(nCt > 0, sC / np.maximum(nCt, 1), 0.0)
        wt = np.minimum(nP, CAP)
        mw_num += float((wt * Bt).sum()); mw_den += float(wt.sum())
        ew_num += float(sP.sum()); ew_den += float(nP.sum())
        for rec in recs:
            act = has & (Sglob >= rec.start)
            hr = np.nonzero(act)[0]
            if hr.size:
                ok = rec.S[hr] < S_RUN + 1
                hr2 = hr[ok]
                rec.X[hr2, rec.S[hr2]] = Bt[hr2]
                rec.W[hr2, rec.S[hr2]] = nP[hr2]
            rec.S[hr] += 1
            am = act.astype(float)
            rec.ca += sP * am; rec.cr += sR * am; rec.ne += nP * act
            rec.ta += tA * am; rec.tr += tR * am
            pm = act[pr]
            if pm.any():
                flat = pr[pm] * U + pi_[pm]
                isum = rec.isum.reshape(-1)
                icnt = rec.icnt.reshape(-1)
                new = icnt[flat] == 0
                np.add.at(isum, flat, pa[pm])
                np.add.at(icnt, flat, 1)
                if new.any():
                    rec.niss += np.bincount(pr[pm][new], minlength=R)
            rec.cbm += np.where(act, Bt, 0.0)
            rec.ccm += np.where(act, Ct, 0.0)
            S = rec.S
            rec.Sat[:, ti] = np.minimum(S, 32767)
            rec.has[:, ti] = act
            mn = (rec.ne >= CF.MIN_EV) & (rec.niss >= CF.MIN_ISS) & (S >= CF.MIN_BLK)
            rec.mn[:, ti] = mn
            ctrl = rec.cbm > rec.ccm
            gd = (rec.ca > 0) & (rec.cr > 0) & (rec.ta > 0) & (rec.tr > 0) & ctrl
            rec.g[:, ti] = gd
            rec.neg[:, ti] = rec.ca < 0
            look = act & mn & (S <= S_RUN)
            cand = np.nonzero(look & (gd | full_p))[0]
            if cand.size:
                rec.P[cand, ti] = 1.0
                for Sv in np.unique(S[cand]):
                    rs = cand[S[cand] == Sv]
                    Y = np.minimum(rec.W[rs, :Sv], CAP) * (rec.X[rs, :Sv] - MARGIN)
                    zz = Y.sum(axis=1) / np.sqrt(np.maximum((Y * Y).sum(axis=1), 1e-300))
                    keep = np.ones(rs.size, bool) if full_p else zz >= CF.Z_PRE
                    if keep.any():
                        rec.P[rs[keep], ti] = CF.signflip_p_rows(Y[keep], int(Sv))
            cand = np.nonzero(look & (rec.ca < 0))[0]
            if cand.size:
                rec.Q[cand, ti] = 1.0
                for Sv in np.unique(S[cand]):
                    rs = cand[S[cand] == Sv]
                    Y = -np.minimum(rec.W[rs, :Sv], CAP) * rec.X[rs, :Sv]
                    zz = Y.sum(axis=1) / np.sqrt(np.maximum((Y * Y).sum(axis=1), 1e-300))
                    keep = np.ones(rs.size, bool) if full_p else zz >= CF.Z_PRE
                    if keep.any():
                        rec.Q[rs[keep], ti] = CF.signflip_p_rows(Y[keep], int(Sv))
            need = np.nonzero(look & gd & (rec.P[:, ti] <= CF.ALPHA_MAX + TIE))[0]
            for r in need:
                c = rec.icnt[r]
                nz = c > 0
                rec.iss[r, ti] = CF.issuer_p(rec.isum[r][nz] / c[nz], gflips) <= CF.ISS_G
            if rec.unweighted:
                gu = (rec.ca > 0) & (rec.cr > 0) & ctrl
                rec.gu[:, ti] = gu
                cand = np.nonzero(look & gu)[0]
                if cand.size:
                    rec.Pu[cand, ti] = 1.0
                    for Sv in np.unique(S[cand]):
                        rs = cand[S[cand] == Sv]
                        Y = rec.X[rs, :Sv] - MARGIN
                        zz = Y.sum(axis=1) / np.sqrt(np.maximum((Y * Y).sum(axis=1), 1e-300))
                        keep = zz >= CF.Z_PRE
                        if keep.any():
                            rec.Pu[rs[keep], ti] = CF.signflip_p_rows(Y[keep], int(Sv))
                need = np.nonzero(look & gu & (rec.Pu[:, ti] <= CF.ALPHA_MAX + TIE))[0]
                for r in need:
                    c = rec.icnt[r]
                    nz = c > 0
                    rec.issu[r, ti] = CF.issuer_p(rec.isum[r][nz] / c[nz], gflips) <= CF.ISS_G
        Sglob += has
    out = recs[0].arrays("")
    if run2:
        out.update(recs[1].arrays("_2"))
    info = {"mean_read_n": float(recs[0].ne.mean() / T), "mu_family": mu_family,
            "mw_mean_a_bp": 1e4 * mw_num / max(mw_den, 1e-300), "ew_mean_a_bp": 1e4 * ew_num / max(ew_den, 1e-300),
            "crash_share": crash_n / float(R * T)}
    return out, info


